// Self-host Wikimedia Commons images.
//
// Browsers hot-linking ~100 Commons images per page through Special:FilePath get
// rate-limited (HTTP 429), which shows up as broken images. This script downloads
// each freely-licensed Commons image ONCE, at a polite pace, and writes resized
// WebP copies to public/img/wm/<key>-<width>.webp. lib/imageLoader.ts then serves
// those local copies (Vercel static files: no Image Optimization usage) and only
// falls back to Commons for images that haven't been localized yet.
//
// Attribution/licence data is unchanged: the DB and lib/imageData.ts keep the
// original Commons URL + source page, which the credits UI links to.
//
//   npx tsx scripts/localize-images.ts          # fetch anything missing
//
// Re-run after adding new Commons images (e.g. after an ingest), then commit
// public/img/wm/ and lib/localImages.ts.
import fs from "node:fs";
import path from "node:path";
import sharp from "sharp";
import { createPrismaClient } from "../lib/prisma";
import { imageKey, LOCAL_IMAGE_WIDTHS } from "../lib/imageKey";
import { filmImages, personImages } from "../lib/imageData";

try {
  process.loadEnvFile();
} catch {
  /* env optional */
}

const OUT_DIR = path.join(process.cwd(), "public", "img", "wm");
const MANIFEST = path.join(process.cwd(), "lib", "localImages.ts");
const UA = "KotfilmImageSync/1.0 (https://kotfilm-iota.vercel.app; one-off image localization)";
const COMMONS = /^https:\/\/upload\.wikimedia\.org\/wikipedia\/[^/]+\/[0-9a-f]\/[0-9a-f]{2}\/([^/]+)$/;

const sleep = (ms: number) => new Promise((r) => setTimeout(r, ms));

async function download(file: string): Promise<Buffer> {
  // 1280 is a standard Commons thumbnail step; small originals come back unscaled.
  const url = `https://commons.wikimedia.org/wiki/Special:FilePath/${file}?width=1280`;
  for (let attempt = 1; attempt <= 6; attempt++) {
    const res = await fetch(url, {
      headers: { "User-Agent": UA },
      signal: AbortSignal.timeout(60_000),
    });
    if (res.ok && (res.headers.get("content-type") ?? "").startsWith("image/")) {
      return Buffer.from(await res.arrayBuffer());
    }
    await res.body?.cancel();
    if (res.status === 429 || res.status >= 500) {
      const wait = 15_000 * attempt;
      console.log(`  ${res.status}, retrying in ${wait / 1000}s`);
      await sleep(wait);
      continue;
    }
    throw new Error(`HTTP ${res.status}`);
  }
  throw new Error("gave up after repeated 429/5xx");
}

async function main() {
  const urls = new Set<string>();
  for (const img of [...Object.values(filmImages), ...Object.values(personImages)]) {
    if (COMMONS.test(img.url)) urls.add(img.url);
  }
  if (process.env.DATABASE_URL) {
    const prisma = createPrismaClient();
    const assets = await prisma.imageAsset.findMany({ select: { url: true } });
    for (const a of assets) if (COMMONS.test(a.url)) urls.add(a.url);
    await prisma.$disconnect();
  }

  fs.mkdirSync(OUT_DIR, { recursive: true });
  const done: string[] = [];
  const failed: string[] = [];
  let n = 0;
  for (const url of [...urls].sort()) {
    n++;
    const key = imageKey(url);
    const outputs = LOCAL_IMAGE_WIDTHS.map((w) => path.join(OUT_DIR, `${key}-${w}.webp`));
    if (outputs.every((p) => fs.existsSync(p))) {
      done.push(key);
      continue;
    }
    const file = url.match(COMMONS)![1];
    console.log(`[${n}/${urls.size}] ${decodeURIComponent(file)}`);
    try {
      const src = await download(file);
      for (const [i, w] of LOCAL_IMAGE_WIDTHS.entries()) {
        // failOn "none": tolerate slightly malformed (but displayable) JPEGs.
        await sharp(src, { failOn: "none" })
          .rotate()
          .resize({ width: w, withoutEnlargement: true })
          .webp({ quality: 72 })
          .toFile(outputs[i]);
      }
      done.push(key);
    } catch (e) {
      failed.push(`${url}  (${e instanceof Error ? e.message : e})`);
    }
    await sleep(1500); // stay well under Commons' rate limits
  }

  const keys = [...new Set(done)].sort();
  fs.writeFileSync(
    MANIFEST,
    `// AUTO-GENERATED by scripts/localize-images.ts — do not edit by hand.\n` +
      `// Keys (see lib/imageKey.ts) of Commons images self-hosted in public/img/wm/.\n` +
      `export const localImageKeys: ReadonlySet<string> = new Set([\n` +
      keys.map((k) => `  "${k}",`).join("\n") +
      `\n]);\n`,
  );
  console.log(`\nlocalized: ${keys.length}/${urls.size}`);
  if (failed.length) console.log(`failed (will keep loading from Commons):\n${failed.join("\n")}`);
}

main().catch((e) => {
  console.error(e);
  process.exit(1);
});
